// The survey of the aircraft and of the pilot, for the flight model and the pilot's seat (js/survey.js).
//
//   node scripts/flight_survey.mjs template [--check]         write data/flight_survey_template.csv, the sheet to fill in
//   node scripts/flight_survey.mjs sheet [--check]            write the tables of docs/10_flight_survey.md
//   node scripts/flight_survey.mjs import <sheet.csv> [file]  add the filled rows of a sheet to the survey file
//   node scripts/flight_survey.mjs validate [file]            check the survey file
//   node scripts/flight_survey.mjs report [file] [--include-raw]   the survey beside the model
//
// The survey file is data/flight_survey.json unless another is named.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SURVEY, CONDITIONS, validateSurvey, compareSurvey, measuredNumbers, templateRows, toCsv, fromCsv } from '../js/survey.js';

const at = (p) => fileURLToPath(new URL(p, import.meta.url));
const FILE = at('../data/flight_survey.json'), TEMPLATE = at('../data/flight_survey_template.csv'), DOC = at('../docs/10_flight_survey.md');
const read = (p) => JSON.parse(readFileSync(p, 'utf8'));
const KIND = { ground: ['On the ground, engine off', 'على الأرض والمحرك متوقف'], seat: ['The pilot in the seat', 'الطيار في مقعده'], flight: ['In flight and on the runway', 'في الطيران وعلى المدرج'] };
const NEED = { flap_deg: ['flaps (°)', 'القلابات (°)'], weight_lb: ['weight (lb)', 'الوزن (رطل)'], cg_in: ['centre of gravity (in)', 'مركز الثقل (بوصة)'], pressure_altitude_ft: ['pressure altitude (ft)', 'الارتفاع الضغطي (قدم)'],
  oat_c: ['outside air temperature (°C)', 'حرارة الهواء الخارجي (°م)'], kias: ['indicated airspeed (kt)', 'السرعة المبيَّنة (عقدة)'], rpm: ['RPM', 'الدورات'], headwind_kt: ['headwind (kt)', 'الريح المقابلة (عقدة)'] };
const UNIT = { deg: ['degrees', 'درجة'], s: ['seconds', 'ثانية'], in: ['inches', 'بوصة'], rpm: ['RPM', 'دورة في الدقيقة'], kt: ['knots', 'عقدة'], ft_min: ['ft/min', 'قدم/دقيقة'], ft: ['feet', 'قدم'] };

/** The tables of what to measure, in English and in Arabic. */
export function sheetMarkdown() {
  const out = [];
  for (const [lang, i] of [['en', 0], ['ar', 1]]) {
    out.push(lang === 'en' ? '### What to measure' : '### ما الذي يُقاس', '');
    for (const kind of ['ground', 'seat', 'flight']) {
      out.push(`**${KIND[kind][i]}**`, '');
      out.push(lang === 'en' ? '| Record as | What | How | Unit | Note with it | In the model |' : '| يُسجَّل باسم | ماذا | كيف | الوحدة | يُدوَّن معه | في النموذج |', '|---|---|---|---|---|---|');
      for (const [name, d] of Object.entries(SURVEY)) {
        if (d.kind !== kind) continue;
        const needs = d.needs.map((k) => NEED[k][i]).join(lang === 'en' ? ', ' : '، ') || '—';
        const effect = d.replaces ? (lang === 'en' ? `replaces \`${d.replaces}\`` : `يحلّ محل \`${d.replaces}\``) : (lang === 'en' ? 'compared' : 'يُقارَن');
        out.push(`| \`${name}\` | ${d[lang]} | ${d[`how_${lang}`]} | ${UNIT[d.unit][i]} (${d.range[0]} ${lang === 'en' ? 'to' : 'إلى'} ${d.range[1]}) | ${needs} | ${effect} |`);
      }
      out.push('');
    }
  }
  return out.join('\n').trimEnd();
}

function fill(text, name, body) {
  const begin = `<!-- ${name}:begin (generated by scripts/flight_survey.mjs) -->`, end = `<!-- ${name}:end -->`;
  const i = text.indexOf(begin), j = text.indexOf(end);
  if (i < 0 || j < 0) throw new Error(`missing ${name} block`);
  return `${text.slice(0, i + begin.length)}\n${body}\n${text.slice(j)}`;
}

const fmt = (v, unit) => (Number.isFinite(v) ? (unit === 'rpm' || unit === 'ft' || unit === 'ft_min' ? v.toFixed(0) : v.toFixed(1)) : 'out of the model\'s reach');
/** The survey beside the model, as a table. */
export function reportMarkdown(doc, { includeRaw = false } = {}) {
  const rows = compareSurvey(doc, { includeRaw }), m = measuredNumbers(doc);
  const out = [`Records: ${doc.records.length}; counted here: ${rows.length}${includeRaw ? ' (raw ones included: a preview, not a result)' : ' (verified only)'}.`, ''];
  if (!rows.length) { out.push('Nothing to compare: the survey has no verified observation. Nothing in the flight model or the seat is measured.'); return out.join('\n'); }
  out.push('| Record | What | Measured | Model | Difference | Tolerance | Within | Effect |', '|---|---|---|---|---|---|---|---|');
  for (const r of rows) {
    const d = SURVEY[r.parameter];
    out.push(`| ${r.id}${r.status === 'raw' ? ' (raw)' : ''} | ${d.en} | ${fmt(r.value, r.unit)} ${r.unit} | ${fmt(r.model, r.unit)} | ${Number.isFinite(r.model) ? (r.difference >= 0 ? '+' : '−') + fmt(Math.abs(r.difference), r.unit) : '—'} | ±${r.tolerance} | ${r.within == null ? '—' : r.within ? 'yes' : 'no'} | ${r.replaces ? `replaces ${r.replaces}` : 'compared only'} |`);
  }
  const names = [...Object.keys(m.fm), ...Object.keys(m.seat)];
  out.push('', names.length ? `Measured, and replacing the model's own numbers: ${names.join(', ')}.` : 'No number of the model is replaced.');
  return out.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [cmd, ...rest] = process.argv.slice(2);
  const flags = rest.filter((a) => a.startsWith('--')), args = rest.filter((a) => !a.startsWith('--'));
  const check = flags.includes('--check');
  const same = (path, text, what) => { if (readFileSync(path, 'utf8') !== text) { console.error(`${what} is stale: run node scripts/flight_survey.mjs ${cmd}`); process.exit(1); } console.log(`${what} is up to date`); };
  if (cmd === 'template') { const text = toCsv(templateRows()); if (check) same(TEMPLATE, text, 'data/flight_survey_template.csv'); else { writeFileSync(TEMPLATE, text); console.log('wrote', TEMPLATE); } }
  else if (cmd === 'sheet') { const text = fill(readFileSync(DOC, 'utf8'), 'sheet', sheetMarkdown()); if (check) same(DOC, text, 'docs/10_flight_survey.md'); else { writeFileSync(DOC, text); console.log('wrote', DOC); } }
  else if (cmd === 'import') {
    if (!args[0]) { console.error('name the filled sheet: import <sheet.csv> [file]'); process.exit(2); }
    const file = args[1] || FILE, doc = read(file), records = fromCsv(readFileSync(args[0], 'utf8'));
    const ids = new Set(records.map((r) => r.id));
    const next = { ...doc, records: [...doc.records.filter((r) => !ids.has(r.id)), ...records] };
    const errors = validateSurvey(next);
    if (errors.length) { console.error(`not imported: ${errors.length} problem(s)\n- ${errors.join('\n- ')}`); process.exit(1); }
    writeFileSync(file, `${JSON.stringify(next, null, 2)}\n`);
    console.log(`imported ${records.length} record(s) into ${file}; ${next.records.length} in all`);
  } else if (cmd === 'validate') {
    const errors = validateSurvey(read(args[0] || FILE));
    if (errors.length) { console.error(`${errors.length} problem(s)\n- ${errors.join('\n- ')}`); process.exit(1); }
    const doc = read(args[0] || FILE), n = (s) => doc.records.filter((r) => r.verification_status === s).length;
    console.log(`the survey is sound: ${doc.records.length} record(s): ${n('verified')} verified, ${n('raw')} raw, ${n('rejected')} rejected`);
  } else if (cmd === 'report') {
    const doc = read(args[0] || FILE), errors = validateSurvey(doc);
    if (errors.length) { console.error(`the survey is not sound:\n- ${errors.join('\n- ')}`); process.exit(1); }
    console.log(reportMarkdown(doc, { includeRaw: flags.includes('--include-raw') }));
  } else { console.error('usage: flight_survey.mjs template|sheet|import|validate|report (see the head of the file)'); process.exit(2); }
}
export { CONDITIONS };
