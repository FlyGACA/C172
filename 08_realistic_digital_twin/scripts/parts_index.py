#!/usr/bin/env python3
"""Write the parts index (docs/06_parts_index.md) from models/parts_all.json, the list of every part
that the model build writes.

    python3 08_realistic_digital_twin/scripts/parts_index.py            write the index
    python3 08_realistic_digital_twin/scripts/parts_index.py --check    fail if the index is out of date

The index is what to look in for the id of a part: the ids are what the part tool
(09_book_figures/blender/part.py), the figure recipes and the web viewer use.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

P8 = Path(__file__).resolve().parents[1]
SOURCE = P8 / "models" / "parts_all.json"
TARGET = P8 / "docs" / "06_parts_index.md"

LEVELS = {0: "basic model", 1: "under the skin: structure, mechanisms, systems", 2: "fasteners, the hardware kit and what is fitted only on the ground"}
SYSTEM_TITLES = {
    "AIRFRAME": "Airframe", "WING_L": "Left wing", "WING_R": "Right wing", "EMPENNAGE": "Empennage", "GEAR": "Landing gear", "POWERPLANT": "Powerplant",
    "ENGINE": "Engine", "IGNITION": "Ignition", "INDUCTION": "Induction", "OIL": "Oil", "FUEL": "Fuel", "ELECTRICAL": "Electrical", "VACUUM": "Vacuum",
    "PITOT_STATIC": "Pitot-static", "STALL_WARNING": "Stall warning", "CABIN_AIR": "Cabin heating, ventilating and defrosting", "AVIONICS": "Avionics", "GROUND_EQUIPMENT": "Ground equipment (fitted or used only on the ground)", "CONTROLS": "Flight controls and flap drive", "BRAKES": "Brakes", "INTERIOR": "Interior",
    "PANEL": "Instrument panel", "INSTRUMENTS": "Inside the instruments", "FASTENERS": "Fasteners", "HARDWARE": "Standard hardware (kit)", "SYSTEMS": "Systems",
}


def cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def render(data: dict) -> str:
    parts = [p for p in data["parts"] if "detail" in p]
    summary = data["summary"]
    lines = [
        "# Parts index",
        "",
        "Every part of the Phase 8 model, with the id to use for it. Generated by `scripts/parts_index.py` from",
        "`models/parts_all.json`, which the model build writes; do not edit by hand.",
        "",
        f"**{summary['parts']} parts.** By detail level: "
        + "; ".join(f"level {level}: {count} ({LEVELS.get(int(level), '')})" for level, count in summary["by_detail"].items()) + ".",
        "",
        "How to use an id (see `09_book_figures/README.md`):",
        "",
        "```",
        "npm run part -- render --part ENGINE.piston_1                      one part, drawn alone",
        "npm run part -- render --part \"WING_L.rib_*\" --context             every left wing rib, in the phantom aircraft",
        "npm run part -- render --part @fuel_system --context --grow 0.006  a whole assembly, wherever its parts are",
        "npm run part -- render --part @altimeter --ghost PANEL.ALT.case    a mechanism, with its case as a phantom",
        "npm run part -- export --part @aileron_control --out aileron.glb   the same parts as a 3D file",
        "```",
        "",
        "Status: `poh` the handbook shows or names it; `type_data` from the type's published data; `measured` measured on the aircraft;",
        "`estimated` representative: its existence is known, its position and size are not from a drawing.",
        "",
        "## Assemblies",
        "",
        "An assembly gathers the parts of one system wherever they are in the aircraft. Select one with `@name`.",
        "",
        "| Assembly | Parts |",
        "|---|---|",
    ]
    lines += [f"| `@{name}` | {count} |" for name, count in summary["assemblies"].items()]
    systems: dict[str, list[dict]] = {}
    for part in parts:
        systems.setdefault(part["system"], []).append(part)
    lines += ["", "## Systems", "", "Select every part of a system with `system:NAME`.", "", "| System | Parts |", "|---|---|"]
    lines += [f"| [`system:{name}`](#{name.lower()}) {SYSTEM_TITLES.get(name, '')} | {len(systems[name])} |" for name in sorted(systems)]
    for name in sorted(systems):
        lines += ["", f"## {name}", "", f"{SYSTEM_TITLES.get(name, name)}: {len(systems[name])} parts.", "", "| Id | English | العربية | Level | Status |", "|---|---|---|---|---|"]
        for part in sorted(systems[name], key=lambda p: p["id"]):
            lines.append(f"| `{cell(part['id'])}` | {cell(part['en'])} | {cell(part['ar'])} | {part['detail']} | {cell(part.get('status', ''))} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    text = render(json.loads(SOURCE.read_text(encoding="utf-8")))
    if "--check" in argv:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            print(f"{TARGET.relative_to(P8.parent)} is out of date: run python3 08_realistic_digital_twin/scripts/parts_index.py", file=sys.stderr)
            return 1
        print("Parts index is up to date")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(P8.parent)} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
