// The survey of the aircraft and of the pilot (js/survey.js): what a record must be, what a verified record
// replaces, and how a flight observation is set beside the model.
//
// The numbers in these tests are made up to exercise the code, or are the handbook's own figures used as if
// they had been observed. None is a measurement of an aircraft. The survey file itself has no record.
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import * as F from '../js/flight.js';
import * as POH from '../js/poh_tables.js';
import { HEAD, REACH, CABIN, canReach, shoulders, floorAt } from '../js/seat.js';
import { SURVEY, CONDITIONS, COLUMNS, validateSurvey, compareSurvey, measuredNumbers, applySurvey, resetSurvey, templateRows, toCsv, fromCsv } from '../js/survey.js';
import { sheetMarkdown } from '../scripts/flight_survey.mjs';

const at = (p) => new URL(p, import.meta.url);
const near = (a, b, tol, what) => assert.ok(Math.abs(a - b) <= tol, `${what}: ${a} against ${b} (±${tol})`);
const rec = (id, parameter, value, conditions = {}, more = {}) => ({ id, parameter, value, unit: SURVEY[parameter]?.unit ?? 'deg', tolerance: 1, conditions, method: 'test fixture, not a measurement', recorded_at: '2026-01-01', recorded_by: 'test', verification_status: 'verified', notes: '', ...more });
const survey = (records, aircraft = { tail_number: 'TEST', serial_number: 'TEST' }) => ({ schema_version: 1, aircraft, records });
const sources = () => F.coefficientTable().reduce((n, r) => ({ ...n, [r.source]: (n[r.source] || 0) + 1 }), {});

test('the survey file has no record: nothing in the flight model or the seat is measured', () => {
  const doc = JSON.parse(readFileSync(at('../data/flight_survey.json'), 'utf8'));
  assert.deepEqual(validateSurvey(doc), []);
  assert.deepEqual(doc.records, [], 'no record until an aircraft is surveyed');
  assert.deepEqual(doc.aircraft, { tail_number: null, serial_number: null }, 'and no aircraft named');
  assert.deepEqual(applySurvey(doc), { flight: [], seat: [], records: [] });
  assert.deepEqual(sources(), { poh: 12, derived: 16, estimated: 55 }, 'the 83 numbers keep their sources');
  assert.equal(HEAD.measured, undefined);
  assert.deepEqual(compareSurvey(doc), []);
});

test('the sheet to fill in: every thing to measure, no value in it; the files written from it are current', () => {
  const rows = templateRows();
  for (const p of Object.keys(SURVEY)) assert.ok(rows.some((r) => r.parameter === p), `${p} is on the sheet`);
  for (const r of rows) { assert.equal(r.value, '', `${r.id} has no value`); assert.equal(r.tolerance, ''); assert.equal(r.unit, SURVEY[r.parameter].unit); assert.equal(r.verification_status, 'raw'); }
  assert.equal(new Set(rows.map((r) => r.id)).size, rows.length, 'each row has its own name');
  const csv = readFileSync(at('../data/flight_survey_template.csv'), 'utf8');
  assert.equal(csv, toCsv(rows), 'data/flight_survey_template.csv is current: node scripts/flight_survey.mjs template');
  assert.equal(csv.split('\n')[0], COLUMNS.join(','));
  assert.deepEqual(fromCsv(csv), [], 'a sheet with nothing filled in gives no record');
  const doc = readFileSync(at('../docs/10_flight_survey.md'), 'utf8');
  assert.ok(doc.includes(`(generated by scripts/flight_survey.mjs) -->\n${sheetMarkdown()}\n<!-- sheet:end -->`), 'docs/10_flight_survey.md is current: node scripts/flight_survey.mjs sheet');
  // every thing to measure is described in both languages, with how to measure it
  for (const [p, d] of Object.entries(SURVEY)) for (const k of ['en', 'ar', 'how_en', 'how_ar']) assert.ok(typeof d[k] === 'string' && d[k].length > 5, `${p}.${k}`);
  for (const d of Object.values(SURVEY)) { assert.match(d.ar, /[؀-ۿ]/); for (const n of d.needs) assert.ok(n in CONDITIONS); }
});

test('a filled sheet is read into records; a record that is not sound is refused, with the reason', () => {
  const rows = templateRows().map((r) => ({ ...r }));
  const fillIn = (id, more) => Object.assign(rows.find((r) => r.id === id), { tolerance: 1, method: 'inclinometer, "digital"', recorded_at: '2026-02-03', recorded_by: 'A, B', ...more });
  fillIn('elevator-up-deg', { value: 27 });
  fillIn('stall-flaps-40', { value: 41, weight_lb: 2100, cg_in: 42 });
  const records = fromCsv(toCsv(rows));
  assert.equal(records.length, 2, 'only the rows with a value');
  assert.deepEqual(records[0], { id: 'elevator-up-deg', parameter: 'elevator_up_deg', value: 27, unit: 'deg', tolerance: 1, conditions: {}, method: 'inclinometer, "digital"', recorded_at: '2026-02-03', recorded_by: 'A, B', verification_status: 'raw', notes: '' });
  assert.deepEqual(records[1].conditions, { flap_deg: 40, weight_lb: 2100, cg_in: 42 });
  assert.deepEqual(validateSurvey(survey(records, { tail_number: null, serial_number: null })), [], 'raw records of an aircraft not yet named are sound');
  // what is wrong is said
  const wrong = (record, pattern, aircraft) => { const errors = validateSurvey(survey([record], aircraft)); assert.ok(errors.some((e) => pattern.test(e)), `${pattern} in ${JSON.stringify(errors)}`); };
  wrong(rec('a', 'elevator_up_deg', 27, {}, { unit: 'rad' }), /the unit of elevator_up_deg is deg/);
  wrong(rec('a', 'elevator_up_deg', 0.47), /outside 20 to 32: check the reading and the unit/);
  wrong(rec('a', 'stall_kias', 44, { flap_deg: 0, weight_lb: 2300 }), /stall_kias needs cg_in/);
  wrong(rec('a', 'stall_kias', 44, { flap_deg: 0, weight_lb: 2600, cg_in: 40 }), /weight_lb 2600 is outside/);
  wrong(rec('a', 'climb_fpm', 700, { kias: 73, pressure_altitude_ft: 2000, oat_c: 11, weight_lb: 2300, moon_phase: 1 }), /"moon_phase" is not a condition/);
  wrong(rec('a', 'wing_colour', 3), /is not something this survey records/);
  wrong(rec('A b', 'elevator_up_deg', 27), /id must be/);
  wrong(rec('a', 'elevator_up_deg', 27, {}, { recorded_at: '3 Feb' }), /recorded_at must be a date/);
  wrong(rec('a', 'elevator_up_deg', 27, {}, { verification_status: 'checked' }), /verification_status must be one of/);
  wrong(rec('a', 'elevator_up_deg', 27, {}, { tolerance: -1 }), /tolerance must be zero or more/);
  wrong(rec('a', 'elevator_up_deg', 27, {}, { method: ' ' }), /how it was measured is missing/);
  wrong(rec('a', 'elevator_up_deg', 27), /needs the registration and the serial number/, { tail_number: null, serial_number: null });
  assert.ok(validateSurvey(survey([rec('a', 'elevator_up_deg', 27), rec('a', 'elevator_down_deg', 22)])).some((e) => /used twice/.test(e)));
  // a measurement of the pilot does not need the aircraft named
  assert.deepEqual(validateSurvey(survey([rec('a', 'arm_reach_in', 27)], { tail_number: null, serial_number: null })), []);
  assert.throws(() => applySurvey(survey([rec('a', 'elevator_up_deg', 99)])), /the survey is not sound/);
});

test('only verified ground and seat measurements replace numbers; those numbers then read "measured"', () => {
  const doc = survey([
    rec('up-1', 'elevator_up_deg', 26), rec('up-2', 'elevator_up_deg', 27),                       // twice: the mean counts
    rec('down', 'elevator_down_deg', 20, {}, { verification_status: 'raw' }),                      // not yet checked: ignored
    rec('flaps', 'flap_time_s', 10, {}, { verification_status: 'rejected' }),                      // a wrong reading: ignored
    rec('reach', 'arm_reach_in', 26), rec('panel', 'eye_to_panel_in', 24), rec('height', 'eye_above_floor_in', 40),
    rec('stall', 'stall_kias', 46, { flap_deg: 0, weight_lb: 2300, cg_in: 40 }),                   // a flight observation: replaces nothing
  ]);
  assert.deepEqual(validateSurvey(doc), []);
  const m = measuredNumbers(doc);
  assert.deepEqual(m.fm, { elevatorUpDeg: { v: 26.5, ref: 'survey: up-1, up-2' } });
  assert.deepEqual(Object.keys(m.seat).sort(), ['eye', 'reach']);
  try {
    const before = { eye: [...HEAD.eye], up: F.FM.elevatorUpDeg.v };
    assert.deepEqual(applySurvey(doc), { flight: ['elevatorUpDeg'], seat: ['eye', 'reach'], records: ['up-1', 'up-2', 'reach', 'panel', 'height'] });
    // the flight model: one number measured, the rest as they were, and the model flies with it
    assert.deepEqual(sources(), { poh: 12, derived: 16, estimated: 54, measured: 1 });
    const row = F.coefficientTable().find((r) => r.name === 'elevatorUpDeg');
    assert.deepEqual([row.value, row.source, row.ref], [26.5, 'measured', 'survey: up-1, up-2']);
    assert.equal(F.FM.elevatorUpDeg.was, before.up, 'what the model was built with is kept');
    near(F.elevatorAngle({ elevator: 1, trim: 0 }), (-26.5 * Math.PI) / 180, 1e-12, 'the wheel fully back gives the measured travel');
    assert.equal(F.FM.elevatorDownDeg.src, 'estimated', 'a raw record changes nothing');
    assert.equal(F.FM.flapRateDegS.v, 5, 'a rejected record changes nothing');
    // the seat: the eye where it was measured from the panel and the floor, the arm as measured
    near(HEAD.eye[2], CABIN.panelFaceZ - 24 * 0.0254, 1e-12, 'eye, back from the panel');
    near(HEAD.eye[1], floorAt(HEAD.eye[2]) + 40 * 0.0254, 1e-12, 'eye, above the floor');
    assert.equal(HEAD.eye[0], before.eye[0], 'what was not measured stays');
    near(HEAD.reach, 26 * 0.0254, 1e-12, 'reach');
    assert.deepEqual(HEAD.measured, ['eye', 'reach']);
    const [, right] = shoulders({ forward: 0, side: 0 });
    assert.ok(canReach([right[0], right[1], right[2] + 0.65]) && !canReach([right[0], right[1], right[2] + 0.67]), 'the hand reaches as far as the measured arm');
    assert.equal(REACH, 0.72, 'the estimate the model was built with is still on record');
  } finally { resetSurvey(); }
  assert.deepEqual(sources(), { poh: 12, derived: 16, estimated: 55 }, 'put back');
  assert.deepEqual([F.FM.elevatorUpDeg.v, F.FM.elevatorUpDeg.src, HEAD.reach, HEAD.measured], [28, 'estimated', 0.72, undefined]);
  // a number fitted to the handbook's tables is not one a ground survey can replace
  assert.throws(() => F.applyMeasured({ CD0: { v: 0.03 } }), /not a number a ground survey can replace/);
  assert.deepEqual(F.MEASURABLE, ['elevatorUpDeg', 'elevatorDownDeg', 'flapRateDegS']);
});

test('a flight observation is set beside the model at its own weight, altitude and temperature, and replaces nothing', () => {
  const full = F.cgStation(2300, 1);
  const [elev, tempC, weight, roll] = POH.TAKEOFF.rows.find((r) => r[0] === 0 && r[2] === 2300);
  const doc = survey([
    rec('static', 'static_rpm', 2340, { pressure_altitude_ft: 0, oat_c: 15 }, { tolerance: 60 }),
    rec('stall', 'stall_kias', F.kiasFromKcas(POH.STALL_KCAS.aft[0][0]), { flap_deg: 0, weight_lb: 2300, cg_in: full }),
    rec('horn', 'stall_warning_kias', 50, { flap_deg: 0, weight_lb: 2300, cg_in: full }, { tolerance: 3 }),
    rec('climb', 'climb_fpm', POH.CLIMB_STANDARD.rows[0][2], { kias: POH.CLIMB_STANDARD.rows[0][1], pressure_altitude_ft: 0, oat_c: 15, weight_lb: 2300 }, { tolerance: 25 }),
    rec('cruise', 'cruise_kias', 110, { rpm: 2500, pressure_altitude_ft: 4000, oat_c: 7, weight_lb: 2300 }, { tolerance: 3 }),
    rec('cruise-high', 'cruise_kias', 100, { rpm: 2700, pressure_altitude_ft: 12000, oat_c: -9, weight_lb: 2300 }),
    rec('glide', 'glide_sink_fpm', 560, { kias: 65, flap_deg: 0, pressure_altitude_ft: 3000, oat_c: 9, weight_lb: 2300 }, { tolerance: 60 }),
    rec('takeoff', 'takeoff_roll_ft', roll, { weight_lb: weight, pressure_altitude_ft: elev, oat_c: tempC, headwind_kt: 0 }, { tolerance: 0.08 * roll }),
    rec('landing', 'landing_roll_ft', POH.LANDING.rows[0][2], { weight_lb: 2300, pressure_altitude_ft: POH.LANDING.rows[0][0], oat_c: POH.LANDING.rows[0][1], headwind_kt: 0 }, { tolerance: 0.06 * POH.LANDING.rows[0][2] }),
    rec('not-checked', 'static_rpm', 2100, { pressure_altitude_ft: 0, oat_c: 15 }, { verification_status: 'raw' }),
  ]);
  assert.deepEqual(validateSurvey(doc), []);
  const rows = Object.fromEntries(compareSurvey(doc).map((r) => [r.id, r]));
  assert.equal(rows['not-checked'], undefined, 'a raw record is not compared');
  assert.equal(compareSurvey(doc, { includeRaw: true }).length, 10, 'unless a preview is asked for');
  // the handbook's own figures, used as observations at the handbook's conditions, fall within the model's tolerances
  for (const id of ['static', 'stall', 'horn', 'climb', 'cruise', 'takeoff', 'landing', 'glide']) assert.equal(rows[id].within, true, `${id}: observed ${rows[id].value}, model ${rows[id].model.toFixed(1)}`);
  near(rows.stall.model, rows.stall.value, 0.1, 'stall at the handbook weight and centre of gravity');
  assert.ok(Number.isNaN(rows['cruise-high'].model) && rows['cruise-high'].within === null, 'what the model cannot do at full throttle is said, not invented');
  for (const r of Object.values(rows)) { assert.equal(r.kind, 'flight'); assert.equal(r.replaces, null); }
  // the conditions of the record are the conditions the model is flown at
  const at2 = (id, parameter, c) => SURVEY[parameter].model(rec(id, parameter, 0, c));
  assert.ok(at2('a', 'stall_kias', { flap_deg: 0, weight_lb: 1900, cg_in: 40 }) < at2('a', 'stall_kias', { flap_deg: 0, weight_lb: 2300, cg_in: 40 }) - 3, 'lighter: stalls slower');
  assert.ok(at2('a', 'stall_kias', { flap_deg: 40, weight_lb: 2300, cg_in: 40 }) < at2('a', 'stall_kias', { flap_deg: 0, weight_lb: 2300, cg_in: 40 }), 'flaps down: stalls slower');
  const climb = (alt, oat) => at2('a', 'climb_fpm', { kias: 72, pressure_altitude_ft: alt, oat_c: oat, weight_lb: 2300 });
  assert.ok(climb(6000, 3) < climb(0, 15) - 200 && climb(0, 35) < climb(0, 15) - 25, 'higher or hotter: climbs less');
  const run = (wind) => at2('a', 'takeoff_roll_ft', { weight_lb: 2300, pressure_altitude_ft: 0, oat_c: 20, headwind_kt: wind });
  assert.ok(run(10) < run(0) * 0.9, 'a headwind shortens the takeoff roll');
  near(at2('a', 'static_rpm', { pressure_altitude_ft: 0, oat_c: 15 }), 2340, 5, 'static RPM at sea level');
  // nothing was replaced
  assert.deepEqual(measuredNumbers(doc), { fm: {}, seat: {}, records: [] });
  assert.deepEqual(applySurvey(doc), { flight: [], seat: [], records: [] });
  assert.deepEqual(sources(), { poh: 12, derived: 16, estimated: 55 });
});
